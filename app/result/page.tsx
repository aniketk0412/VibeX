"use client";

// The output — in-browser code (file tree + viewer), the full prompt history (model, tokens,
// cost per step), and a download. Mock content for now; the real engine fills this in Phase 4.

import { useEffect, useMemo, useState } from "react";
import Link from "next/link";
import Logo from "@/components/Logo";
import ThemeToggle from "@/components/ThemeToggle";
import styles from "./result.module.css";

type Spec = { idea?: string; platform?: string; coder?: string; reviewer?: string };
type FileNode = { path: string; body: string };

function mockFiles(spec: Spec): FileNode[] {
  const name = (spec.idea ?? "app").toLowerCase().split(" ").slice(0, 3).join("-").replace(/[^a-z0-9-]/g, "") || "app";
  return [
    {
      path: "README.md",
      body: `# ${spec.idea ?? "Your project"}\n\nGenerated by Vibex — from idea to code, automatically.\n\n- Platform: ${spec.platform ?? "Web app"}\n- Built by: ${spec.coder ?? "Claude Sonnet"} · reviewed by ${spec.reviewer ?? "Claude Opus"}\n\n## Getting started\n\n\`\`\`bash\nnpm install\nnpm run dev\n\`\`\`\n`,
    },
    {
      path: "app/page.tsx",
      body: `export default function Home() {\n  return (\n    <main>\n      <h1>${spec.idea ?? "Welcome"}</h1>\n      {/* core UI generated here */}\n    </main>\n  );\n}\n`,
    },
    {
      path: "lib/db.ts",
      body: `import { PrismaClient } from "@prisma/client";\n\nexport const db = new PrismaClient();\n`,
    },
    {
      path: "package.json",
      body: `{\n  "name": "${name}",\n  "private": true,\n  "scripts": { "dev": "next dev", "build": "next build" }\n}\n`,
    },
  ];
}

const HISTORY = [
  { step: "Scaffold the project", role: "Coder", tokens: 3120, cost: 0.03 },
  { step: "Set up the design system", role: "Coder", tokens: 4480, cost: 0.04 },
  { step: "Model the data", role: "Coder", tokens: 5210, cost: 0.05 },
  { step: "Reviewer pass", role: "Reviewer", tokens: 3870, cost: 0.06 },
  { step: "Polish & accessibility", role: "Coder", tokens: 4090, cost: 0.04 },
  { step: "Final build", role: "Reviewer", tokens: 2650, cost: 0.04 },
];

export default function ResultPage() {
  const [spec, setSpec] = useState<Spec>({});
  const [active, setActive] = useState(0);
  const [tab, setTab] = useState<"code" | "history">("code");

  useEffect(() => {
    try {
      setSpec(JSON.parse(sessionStorage.getItem("vibex-spec") ?? "{}"));
    } catch {
      /* ignore */
    }
  }, []);

  const files = useMemo(() => mockFiles(spec), [spec]);
  const totalTokens = HISTORY.reduce((s, h) => s + h.tokens, 0);
  const totalCost = HISTORY.reduce((s, h) => s + h.cost, 0);

  const download = () => {
    const dump = files.map((f) => `// ===== ${f.path} =====\n${f.body}`).join("\n\n");
    const blob = new Blob([dump], { type: "text/plain" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = "vibex-output.txt";
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className={styles.page}>
      <header className={styles.top}>
        <Link href="/" aria-label="Vibex home">
          <Logo size={28} />
        </Link>
        <ThemeToggle />
      </header>

      <main className={styles.main}>
        <div className={styles.head}>
          <div>
            <span className={styles.eyebrow}><span className={styles.ok}>✓</span> Build complete</span>
            <h1 className={styles.title}>{spec.idea ?? "Your project"}</h1>
            <p className={styles.sub}>
              {files.length} files · {(totalTokens / 1000).toFixed(1)}k tokens · ~${totalCost.toFixed(2)} ·
              {" "}{spec.coder ?? "Claude Sonnet"} + {spec.reviewer ?? "Claude Opus"}
            </p>
          </div>
          <div className={styles.headActions}>
            <button type="button" className="btn btn-ghost" onClick={download}>↓ Download</button>
            <Link href="/new" className="btn btn-primary">New project →</Link>
          </div>
        </div>

        <div className={styles.tabs}>
          <button type="button" className={styles.tab} data-active={tab === "code"} onClick={() => setTab("code")}>
            Code
          </button>
          <button type="button" className={styles.tab} data-active={tab === "history"} onClick={() => setTab("history")}>
            Prompt history
          </button>
        </div>

        {tab === "code" ? (
          <div className={styles.codeWrap}>
            <aside className={styles.tree}>
              {files.map((f, i) => (
                <button
                  key={f.path}
                  type="button"
                  className={styles.treeItem}
                  data-active={active === i}
                  onClick={() => setActive(i)}
                >
                  <span className={styles.fileIcon}>›</span>
                  {f.path}
                </button>
              ))}
            </aside>
            <div className={styles.viewer}>
              <div className={styles.viewerBar}>{files[active].path}</div>
              <pre className={styles.code}>{files[active].body}</pre>
            </div>
          </div>
        ) : (
          <div className={styles.history}>
            {HISTORY.map((h, i) => (
              <div key={i} className={styles.hrow}>
                <span className={styles.hnum}>{i + 1}</span>
                <span className={styles.hstep}>{h.step}</span>
                <span className={styles.hrole} data-role={h.role}>{h.role}</span>
                <span className={styles.hmeta}>{(h.tokens / 1000).toFixed(1)}k · ${h.cost.toFixed(2)}</span>
              </div>
            ))}
            <div className={styles.htotal}>
              <span>Total</span>
              <span>{(totalTokens / 1000).toFixed(1)}k tokens · ~${totalCost.toFixed(2)}</span>
            </div>
          </div>
        )}
      </main>
    </div>
  );
}
